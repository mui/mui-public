import { describe, it } from 'vitest';
import { RuleTester } from 'eslint';
import parser from '@typescript-eslint/parser';
import { lintMarkdownForceStatic } from './lintMarkdownForceStatic';

const ruleTester = new RuleTester({
  languageOptions: {
    parser,
    parserOptions: {
      ecmaFeatures: { jsx: true },
    },
  },
});

describe('lintMarkdownForceStatic', () => {
  // eslint-disable-next-line vitest/expect-expect -- RuleTester uses its own assertion library
  it('should pass RuleTester', () => {
    ruleTester.run('force-static', lintMarkdownForceStatic, {
      valid: [
        { code: "export const dynamic = 'force-static';\n" },
        {
          code: `export const metadata = { title: 'Page' };
export const dynamic = "force-static";
`,
        },
        {
          code: `import { Demo } from './Demo';
export const dynamic = 'force-static';
export const metadata = { title: 'Page' };
`,
        },
        // Generated index pages are rewritten by syncPageIndex and are exempt. The marker is a
        // markdown link definition, which only appears inside a string in this JS-parsed fixture.
        {
          code: `const marker = "[//]: # 'The above section is autogenerated, but the remainder of the file can be modified.'";
export const metadata = { robots: { index: false } };
`,
        },
        // Declared next to other variables in the same statement
        { code: "export const a = 1, dynamic = 'force-static';\n" },
      ],
      invalid: [
        {
          code: "export const metadata = { title: 'Page' };\n",
          output: `export const metadata = { title: 'Page' };

export const dynamic = 'force-static';
`,
          errors: [{ messageId: 'missingForceStatic' }],
        },
        // No trailing newline
        {
          code: "export const metadata = { title: 'Page' };",
          output: `export const metadata = { title: 'Page' };

export const dynamic = 'force-static';
`,
          errors: [{ messageId: 'missingForceStatic' }],
        },
        // Empty file
        {
          code: '',
          output: "export const dynamic = 'force-static';\n",
          errors: [{ messageId: 'missingForceStatic' }],
        },
        // Similarly named exports are not the route segment config
        {
          code: 'export const dynamicParams = false;\n',
          output: `export const dynamicParams = false;

export const dynamic = 'force-static';
`,
          errors: [{ messageId: 'missingForceStatic' }],
        },
        {
          code: "export const dynamic = 'force-dynamic';\n",
          output: "export const dynamic = 'force-static';\n",
          errors: [{ messageId: 'notForceStatic' }],
        },
        {
          code: "export const dynamic = 'auto', other = 1;\n",
          output: "export const dynamic = 'force-static', other = 1;\n",
          errors: [{ messageId: 'notForceStatic' }],
        },
        // Non-literal values cannot be statically analyzed by Next.js either
        {
          code: "const mode = 'force-static';\nexport const dynamic = mode;\n",
          output: "const mode = 'force-static';\nexport const dynamic = 'force-static';\n",
          errors: [{ messageId: 'notForceStatic' }],
        },
      ],
    });
  });
});
