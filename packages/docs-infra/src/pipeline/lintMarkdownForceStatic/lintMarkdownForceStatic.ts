import type { Rule } from 'eslint';
import type { ExportNamedDeclaration } from 'estree';

const FORCE_STATIC_EXPORT = "export const dynamic = 'force-static';";

/**
 * Marker written by `syncPageIndex` into generated index pages. Those files are rewritten on every
 * run and only keep their `metadata` export, so an added `dynamic` export would be removed again.
 */
const GENERATED_INDEX_MARKER = /\[\/\/\]: # '[^']*is autogenerated, but/;

/**
 * Finds the `dynamic` variable declarator of an `export const dynamic = ...` statement.
 * Returns `null` for any other export shape.
 */
function getDynamicDeclarator(node: ExportNamedDeclaration) {
  const { declaration } = node;
  if (declaration?.type !== 'VariableDeclaration') {
    return null;
  }
  return (
    declaration.declarations.find(
      (declarator) => declarator.id.type === 'Identifier' && declarator.id.name === 'dynamic',
    ) ?? null
  );
}

/**
 * ESLint rule requiring `page.mdx` files to opt out of dynamic rendering with
 * `export const dynamic = 'force-static';`.
 *
 * Without it, a single use of a request-time API silently turns a documentation page into a
 * dynamically rendered one. Declaring the segment config in the file makes Next.js fail the build
 * instead.
 *
 * Index pages generated by `syncPageIndex` are skipped because they are rewritten from scratch.
 */
export const lintMarkdownForceStatic = {
  meta: {
    type: 'suggestion',
    docs: {
      description: "Require page.mdx files to export `dynamic = 'force-static'`.",
    },
    fixable: 'code',
    messages: {
      missingForceStatic:
        "Page is missing `export const dynamic = 'force-static';`. Run with --fix to add it automatically.",
      notForceStatic:
        "Page exports `dynamic` with a value other than 'force-static'. Run with --fix to replace it automatically.",
    } as const,
    schema: [],
  } as const,
  create(context) {
    const sourceCode = context.sourceCode;

    if (GENERATED_INDEX_MARKER.test(sourceCode.getText())) {
      return {};
    }

    let dynamicDeclarator: NonNullable<ReturnType<typeof getDynamicDeclarator>> | null = null;

    return {
      ExportNamedDeclaration(node: ExportNamedDeclaration & Rule.NodeParentExtension) {
        dynamicDeclarator ??= getDynamicDeclarator(node);
      },

      'Program:exit'() {
        if (!dynamicDeclarator) {
          const text = sourceCode.getText();
          // Appending keeps the fix independent of the page content. MDX allows ESM exports anywhere
          // at the top level of the document.
          const separator = text.endsWith('\n') ? '\n' : '\n\n';
          context.report({
            loc: { line: 1, column: 0 },
            messageId: 'missingForceStatic',
            fix(fixer) {
              return fixer.insertTextAfterRange(
                [0, text.length],
                `${text.length === 0 ? '' : separator}${FORCE_STATIC_EXPORT}\n`,
              );
            },
          });
          return;
        }

        const { init } = dynamicDeclarator;
        if (init?.type === 'Literal' && init.value === 'force-static') {
          return;
        }
        context.report({
          node: dynamicDeclarator,
          messageId: 'notForceStatic',
          fix(fixer) {
            return init ? fixer.replaceText(init, "'force-static'") : null;
          },
        });
      },
    };
  },
} satisfies Rule.RuleModule;
