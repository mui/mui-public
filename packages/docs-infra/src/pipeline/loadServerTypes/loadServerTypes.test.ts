import { describe, it, expect, afterEach } from 'vitest';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { loadServerTypes } from './loadServerTypes';

const TEST_DIR = join(__dirname, '.test-loadServerTypes');
const TYPES_PATH = join(TEST_DIR, 'src', 'app', 'components', 'button', 'types.md');

describe('loadServerTypes', () => {
  afterEach(async () => {
    await rm(TEST_DIR, { recursive: true, force: true });
  });

  it('links the other names a type is exported under to its section', async () => {
    await mkdir(join(TEST_DIR, 'src', 'app', 'components', 'button'), { recursive: true });
    await writeFile(
      TYPES_PATH,
      `# Button API

[//]: types.ts '<-- Autogenerated By (do not edit the following markdown directly)'

## API Reference

### Button

A clickable button.

Also exported as \`ButtonRoot\`, \`default\`.

**Button Props:**

| Prop     | Type      | Default | Description           |
| :------- | :-------- | :------ | :-------------------- |
| disabled | \`boolean\` | -       | Whether it's disabled |
`,
      'utf-8',
    );

    const result = await loadServerTypes({
      typesMarkdownPath: TYPES_PATH,
      rootContext: TEST_DIR,
      sync: false,
    });

    expect(result.exports.Button.type.aliases).toEqual(['ButtonRoot', 'default']);
    expect(result.anchorMap.js).toMatchObject({
      Button: '#button',
      'Button[0]': '#button:props',
      ButtonRoot: '#button',
      'ButtonRoot[0]': '#button:props',
      default: '#button',
      'default[0]': '#button:props',
    });
  });
});
