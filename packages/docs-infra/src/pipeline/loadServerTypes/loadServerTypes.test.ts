import { describe, it, expect, afterEach } from 'vitest';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { loadServerTypes } from './loadServerTypes';

const TEST_DIR = join(__dirname, '.test-loadServerTypes');
const TYPES_PATH = join(TEST_DIR, 'src', 'app', 'components', 'button', 'types.md');

async function loadTypes(markdown: string) {
  await mkdir(join(TEST_DIR, 'src', 'app', 'components', 'button'), { recursive: true });
  await writeFile(TYPES_PATH, markdown, 'utf-8');
  return loadServerTypes({ typesMarkdownPath: TYPES_PATH, rootContext: TEST_DIR });
}

describe('loadServerTypes', () => {
  afterEach(async () => {
    await rm(TEST_DIR, { recursive: true, force: true });
  });

  describe('anchorMap', () => {
    it('links global types referenced by the page to MDN', async () => {
      const result = await loadTypes(`# Button API

[//]: types.ts '<-- Autogenerated By (do not edit the following markdown directly)'

## API Reference

### Button

**Button Props:**

| Prop      | Type                         | Default | Description                         |
| :-------- | :--------------------------- | :------ | :---------------------------------- |
| locale    | \`Intl.LocalesArgument\`     | -       | The locale.                         |
| container | \`HTMLElement \\| null\`     | -       | Formatted with \`Intl.NumberFormat\`. |
`);

      expect(result.anchorMap.js).toEqual({
        Button: '#button',
        'Button[0]': '#button:props',
        HTMLElement: 'https://developer.mozilla.org/docs/Web/API/HTMLElement',
        'Intl.LocalesArgument':
          'https://developer.mozilla.org/docs/Web/JavaScript/Reference/Global_Objects/Intl#locales_argument',
        'Intl.NumberFormat':
          'https://developer.mozilla.org/docs/Web/JavaScript/Reference/Global_Objects/Intl/NumberFormat',
      });
    });

    it('prefers types documented on the page over MDN links', async () => {
      const result = await loadTypes(`# Button API

[//]: types.ts '<-- Autogenerated By (do not edit the following markdown directly)'

## API Reference

### Button

**Button Props:**

| Prop    | Type      | Default | Description    |
| :------ | :-------- | :------ | :------------- |
| onClick | \`Event\` | -       | The handler.   |

### Event

\`\`\`typescript
type Event = { button: number };
\`\`\`
`);

      expect(result.anchorMap.js?.Event).toBe('#event');
    });
  });
});
