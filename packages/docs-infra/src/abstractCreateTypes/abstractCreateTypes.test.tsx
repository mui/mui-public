/* eslint-disable testing-library/render-result-naming-convention -- renders static HTML, not a Testing Library render */
import * as React from 'react';
import * as ReactDOMServer from 'react-dom/server';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { afterEach, describe, expect, it } from 'vitest';
import { loadServerTypes } from '../pipeline/loadServerTypes';
import { abstractCreateTypes } from './abstractCreateTypes';
import type { TypesTableProps } from '../useTypes/useTypes';

const TEST_DIR = join(__dirname, '.test-abstractCreateTypes');
const TYPES_PATH = join(TEST_DIR, 'src', 'app', 'components', 'button', 'types.md');
const HTML_ELEMENT_URL = 'https://developer.mozilla.org/docs/Web/API/HTMLElement';

const BUTTON_TYPES_MARKDOWN = `# Button API

[//]: types.ts '<-- Autogenerated By (do not edit the following markdown directly)'

## API Reference

### Button

**Button Props:**

| Prop      | Type                     | Default | Description    |
| :-------- | :----------------------- | :------ | :------------- |
| container | \`HTMLElement \\| null\` | -       | The container. |
| anchor    | \`Anchor\`               | -       | The anchor.    |
`;

const EXTERNAL_TYPE_LINKS_MARKDOWN = `
## External Type Links

- \`HTMLElement\`: <${HTML_ELEMENT_URL}>
`;

function TypesTable({ type }: TypesTableProps<{}>) {
  if (type?.type !== 'component') {
    return null;
  }
  return Object.entries(type.data.props).map(([name, prop]) => <div key={name}>{prop.type}</div>);
}

function TypePre({ children }: { children: React.ReactNode }) {
  return <pre>{children}</pre>;
}

async function getButtonTypesMarkup(markdown: string): Promise<string> {
  await mkdir(dirname(TYPES_PATH), { recursive: true });
  await writeFile(TYPES_PATH, markdown, 'utf-8');
  const types = await loadServerTypes({ typesMarkdownPath: TYPES_PATH, rootContext: TEST_DIR });

  const ButtonTypes = abstractCreateTypes(
    { TypesTable, TypePre },
    pathToFileURL(join(dirname(TYPES_PATH), 'types.ts')).href,
    {
      precompute: {
        exports: types.exports,
        additionalTypes: types.additionalTypes,
        variantOnlyAdditionalTypes: types.variantOnlyAdditionalTypes,
        anchorMap: types.anchorMap,
        externalTypeLinks: types.externalTypeLinks,
      },
    },
  );
  return ReactDOMServer.renderToStaticMarkup(<ButtonTypes />);
}

describe('abstractCreateTypes', () => {
  afterEach(async () => {
    await rm(TEST_DIR, { recursive: true, force: true });
  });

  describe('external type links', () => {
    it('links the types listed in types.md to their docs', async () => {
      const markup = await getButtonTypesMarkup(
        BUTTON_TYPES_MARKDOWN + EXTERNAL_TYPE_LINKS_MARKDOWN,
      );

      expect(markup).toContain(`<a href="${HTML_ELEMENT_URL}"`);
      expect(markup.match(/<a /g)).toHaveLength(1);
    });

    it('leaves types unlinked without external type links', async () => {
      const markup = await getButtonTypesMarkup(BUTTON_TYPES_MARKDOWN);

      expect(markup).toContain('HTMLElement');
      expect(markup).not.toContain('<a href=');
    });
  });
});
